const fs = require("fs");
const { JSDOM } = require("jsdom");
const html = fs.readFileSync("index.html","utf8");
const dom = new JSDOM(html, { runScripts:"outside-only", url:"http://localhost/" });
const w = dom.window;
w.eval(fs.readFileSync("js/data.js","utf8"));
w.eval(fs.readFileSync("js/store.js","utf8"));
let appSrc = fs.readFileSync("js/app.js","utf8");
appSrc = appSrc.replace("setStatus(btn,uid_,st){", "setStatus(btn,uid_,st){ console.log('SETSTATUS CALLED', typeof btn, uid_, st);");
w.eval(appSrc);
w.document.dispatchEvent(new w.Event("DOMContentLoaded"));
const S=w.SWT_STORE, App=w.App;
const d1=S.getRoutines().find(r=>r.id==="day1");
App.openRoutine(d1.id);
App.startWorkout(d1.id);
const btn = w.document.querySelector(".status-btn.check");
console.log("about to click. inline handler type:", typeof btn.onclick);
btn.click();
console.log("items:", JSON.stringify(S.getSession().items));
process.exit(0);
